#[cfg(test)]
mod tests {
    use std::path::Path;

    use super::*;

    /// Every supported code page converts each byte as the original engine's
    /// `AdsSetStringFromCodePage` did, read back through a Unicode field
    /// (`fixtures/codepage/setfromcodepage.json`, probed with
    /// `tools/ace/codepage`). Byte 0x00 is left out: a stored NUL reads back as
    /// a space, so the golden records 0x20 for it, where the true conversion
    /// (and tflip's table) is U+0000.
    #[test]
    fn tables_match_the_engine() {
        let path = Path::new(env!("CARGO_MANIFEST_DIR"))
            .join("../../fixtures/codepage/setfromcodepage.json");
        let golden: serde_json::Value =
            serde_json::from_str(&std::fs::read_to_string(path).unwrap()).unwrap();
        let pages = golden["pages"].as_array().unwrap();
        assert_eq!(pages.len(), 30);
        for page in pages {
            let cp = page["code_page"].as_u64().unwrap() as u32;
            let units = page["units"].as_array().unwrap();
            let table = table(cp).unwrap_or_else(|| panic!("no table for {cp}"));
            assert_eq!(table[0], 0, "{cp} byte 0");
            for (byte, unit) in units.iter().enumerate().skip(1) {
                let unit = unit.as_u64().unwrap() as u16;
                assert_eq!(table[byte], unit, "code page {cp} byte {byte:#04x}");
            }
        }
    }

    /// Code pages the original engine opens no converter for have no table.
    #[test]
    fn unsupported_code_pages_have_no_table() {
        for cp in [0, 1, 20127, 28591, 28605, 10000, 65001, 20866] {
            assert!(table(cp).is_none(), "{cp}");
        }
    }
}
