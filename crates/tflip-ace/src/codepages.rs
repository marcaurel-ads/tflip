//! The engine's own byte-to-Unicode tables for the single-byte code pages
//! `AdsSetStringFromCodePage` converts from. The original engine accepts the
//! Windows and OEM single-byte code pages listed in [`table`] (and the
//! double-byte 932/936/949/950, which [`crate::dbcs`] converts); it refuses
//! the others (ISO-8859, Macintosh, UTF, KOI8, US-ASCII) by failing to open a
//! converter.
//!
//! These are the engine's own mappings, not Windows': probed byte by byte
//! through the real DLL (`tools/ace/codepage`), they differ from the standard
//! tables in the OEM control characters (0x1A, 0x1C and 0x7F are rotated), map
//! an undefined ANSI byte to the character of its own value, and have the odd
//! quirk of their own (437's 0xE6 is U+03BC, 852's 0xAA is U+FFFD). The 1252
//! and 437 tables match [`tflip_storage::cp1252`] and the OEM-table conversion
//! in [`crate::ansi`] byte for byte, which cross-checks the probe.

/// The byte-to-Unicode table of the single-byte code page `code_page`, or
/// `None` where the engine opens no converter for it (`1565`).
pub(crate) fn table(code_page: u32) -> Option<&'static [u16; 256]> {
    Some(match code_page {
        437 => &CP_437,
        500 => &CP_500,
        737 => &CP_737,
        775 => &CP_775,
        850 => &CP_850,
        852 => &CP_852,
        855 => &CP_855,
        856 => &CP_856,
        857 => &CP_857,
        858 => &CP_858,
        860 => &CP_860,
        861 => &CP_861,
        862 => &CP_862,
        863 => &CP_863,
        864 => &CP_864,
        865 => &CP_865,
        866 => &CP_866,
        869 => &CP_869,
        874 => &CP_874,
        875 => &CP_875,
        1026 => &CP_1026,
        1250 => &CP_1250,
        1251 => &CP_1251,
        1252 => &CP_1252,
        1253 => &CP_1253,
        1254 => &CP_1254,
        1255 => &CP_1255,
        1256 => &CP_1256,
        1257 => &CP_1257,
        1258 => &CP_1258,
        _ => return None,
    })
}

