#!/usr/bin/env python3
"""Writes crates/tflip-engine/src/ace_error/texts.rs from fixtures/errors/texts.json.

    python3 -I tools/ace/errors/texts.py

The fixture's texts are Windows-1252 bytes escaped as \\u00XX; the Rust
table holds them as strings. Needs rustfmt, which formats the output."""
import json
import pathlib
import subprocess

root = pathlib.Path(__file__).resolve().parents[3]
texts = json.loads((root / "fixtures/errors/texts.json").read_text())
rows = []
for code, text in texts.items():
    if not code.isdigit() or not isinstance(text, str):
        continue
    text = text.encode("latin-1").decode("cp1252")
    rows.append((int(code), text))
rows.sort()
out = [
    "//! The original engine's error texts (`AdsGetErrorString`), as",
    "//! `fixtures/errors/texts.json` recorded them; generated by",
    "//! `tools/ace/errors/texts.py`.",
    "",
    "/// Error codes and their texts, by code.",
    "pub static TEXTS: &[(u32, &str)] = &[",
]
for code, text in rows:
    out.append(f"    ({code}, {json.dumps(text, ensure_ascii=False)}),")
out.append("];")
target = root / "crates/tflip-engine/src/ace_error/texts.rs"
target.write_text("\n".join(out) + "\n")
# Wide rows are wrapped by rustfmt, which `cargo fmt` would otherwise do on
# every run and leave the file changed.
subprocess.run(["rustfmt", "--edition", "2024", str(target)], check=True)
