-- FPT block size written by MEMOBLOCKSIZE 1, 2, 31, 32, 33 and 1000 (read
-- from the header at byte 6): FoxPro and Visual FoxPro tables alike take
-- n * 512 for n <= 32 and n itself otherwise.
-- types: cdx vfp
CREATE TABLE mb1 (id INTEGER, m MEMO) MEMOBLOCKSIZE 1;
CREATE TABLE mb2 (id INTEGER, m MEMO) MEMOBLOCKSIZE 2;
CREATE TABLE mb31 (id INTEGER, m MEMO) MEMOBLOCKSIZE 31;
CREATE TABLE mb32 (id INTEGER, m MEMO) MEMOBLOCKSIZE 32;
CREATE TABLE mb33 (id INTEGER, m MEMO) MEMOBLOCKSIZE 33;
CREATE TABLE mb1000 (id INTEGER, m MEMO) MEMOBLOCKSIZE 1000;
