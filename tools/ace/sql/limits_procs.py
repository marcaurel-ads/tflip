print("# How deep procedures and triggers nest, and how long a procedure's script")
print("# is, in a dictionary the script makes (lp/lp.add), in an empty folder with")
print("# a folder lp (generated by limits_procs.py): fixtures/sql/limits_procs.json.")
print("ddcreate lp\\lp.add")
print("stmt")
print("direct CREATE TABLE t (n INTEGER)")
print("direct CREATE PROCEDURE r(n INTEGER) BEGIN DECLARE m INTEGER; m = (SELECT n FROM __input); "
      "IF m > 0 THEN EXECUTE PROCEDURE r(m - 1); END IF; END")
for n in [1, 62, 63, 64, 65, 100]:
    print("direct EXECUTE PROCEDURE r(%d)" % n)
print("direct CREATE TABLE ta (n INTEGER)")
print("direct CREATE TABLE tb (n INTEGER)")
print("direct CREATE TRIGGER tga ON ta AFTER INSERT BEGIN INSERT INTO tb VALUES (1); END")
print("direct CREATE TRIGGER tgb ON tb AFTER INSERT BEGIN INSERT INTO ta VALUES (1); END")
print("direct INSERT INTO ta VALUES (0)")
print("query SELECT COUNT(*) AS c FROM ta")
print("query SELECT COUNT(*) AS c FROM tb")


def body(length):
    """A script of `length` characters."""
    head, tail = "BEGIN SELECT 1 FROM system.iota; /* ", " */ END"
    return head + "x" * (length - len(head) - len(tail)) + tail


# A script of 65,541 characters is kept, one of 65,542 is a property too long,
# and any longer one a script too large.
for create, length in [("CREATE", 65541), ("CREATE", 65542), ("CREATE", 65543)]:
    print("direct %s PROCEDURE s%d() %s" % (create, length, body(length)))
print("direct CREATE PROCEDURE sa() BEGIN SELECT 1 FROM system.iota; END")
for length in [65541, 65542, 65543]:
    print("direct ALTER PROCEDURE sa() %s" % body(length))


def padded(head, tail, length):
    return head + "x" * (length - len(head) - len(tail)) + tail


# A trigger's script of 65,534 characters between BEGIN and END is a property
# too long, one of 65,535 is kept (and fails the statements that fire it), and
# a longer one is more than the container takes. A function's of 65,534 is a
# script too long, as ALTER FUNCTION has it. A view's statement has no limit
# but the statement's own.
print("direct CREATE TABLE tg (n INTEGER)")
for length in [65541, 65542, 65544]:
    print("direct CREATE TRIGGER g%d ON tg AFTER INSERT %s" % (length, body(length)))
print("direct CREATE TRIGGER ga ON tg AFTER INSERT BEGIN SELECT 1 FROM system.iota; END")
for length in [65541, 65542, 65544]:
    print("direct ALTER TRIGGER ga ON tg AFTER INSERT %s" % body(length))
print("direct CREATE TRIGGER g65543 ON tg AFTER DELETE %s" % body(65543))
print("direct INSERT INTO tg VALUES (1)")
print("direct DELETE FROM tg /* fires g65543 */")
print("direct DROP TRIGGER tg.g65543")
print("direct DELETE FROM tg /* after the drop */")
for length in [65541, 65542, 65543]:
    print("direct CREATE FUNCTION f%d() RETURNS INTEGER %s" % (
        length, padded("BEGIN /* ", " */ RETURN 1; END", length)))
print("direct CREATE FUNCTION fa() RETURNS INTEGER BEGIN RETURN 1; END")
for length in [65541, 65542, 65543]:
    print("direct ALTER FUNCTION fa() RETURNS INTEGER %s" % padded("BEGIN /* ", " */ RETURN 1; END", length))
for length in [65542, 65543, 69000]:
    print("direct CREATE VIEW v%d AS %s" % (length, padded("SELECT n FROM tg /* ", " */", length)))
