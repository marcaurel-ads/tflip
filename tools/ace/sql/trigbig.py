#!/usr/bin/env python3
"""Writes trigbig.txt, the script of fixtures/sql/trigbig.json: triggers whose
script is exactly 65,535 bytes, which the original keeps and cannot fire:

    python3 trigbig.py > trigbig.txt
"""


def body(length, name="big"):
    """A script of `length` characters."""
    head, tail = "BEGIN INSERT INTO au (m) VALUES ('%s'); /* " % name, " */ END"
    return head + "x" * (length - len(head) - len(tail)) + tail


def trigger(name, when, big=True):
    return "direct CREATE TRIGGER %s ON tg %s %s" % (name, when, body(65543, name) if big else "BEGIN INSERT INTO au (m) VALUES ('%s'); END" % name)


out = []
w = out.append
w("# Triggers whose script is exactly 65,535 bytes, in a dictionary the script makes")
w("# (bgd/bgd.add), in an empty folder with a folder bgd (generated by trigbig.py):")
w("# fixtures/sql/trigbig.json, and the dictionary it leaves, fixtures/sql/trigbig/.")
w("cachecursors 0")
w("ddcreate bgd\\bgd.add")
w("stmt")
w("direct CREATE TABLE tg (n INTEGER, s CHAR(10))")
w("direct CREATE TABLE au (m CHAR(10))")
w("# --- AFTER INSERT")
w(trigger("big_ai", "AFTER INSERT"))
w("direct INSERT INTO tg VALUES (1, 'a')")
w("query SELECT n FROM tg")
w("query SELECT m FROM au")
w("# the trigger is listed and dropped")
w("query SELECT name FROM system.triggers")
w("direct DROP TRIGGER tg.big_ai")
w("direct DELETE FROM tg")
w("direct DELETE FROM au")
w("# --- BEFORE INSERT: is the row written?")
w(trigger("big_bi", "BEFORE INSERT"))
w("direct INSERT INTO tg VALUES (2, 'b')")
w("query SELECT n FROM tg")
w("query SELECT m FROM au")
w("direct DROP TRIGGER tg.big_bi")
w("direct DELETE FROM tg")
w("# --- BEFORE and AFTER together, and a small one")
w(trigger("sm_bi", "BEFORE INSERT", False))
w(trigger("big_ai", "AFTER INSERT"))
w(trigger("sm_ai", "AFTER INSERT", False))
w("direct INSERT INTO tg VALUES (3, 'c')")
w("query SELECT n FROM tg")
w("query SELECT m FROM au")
w("direct DROP TRIGGER tg.big_ai")
w("direct DROP TRIGGER tg.sm_ai")
w("direct DROP TRIGGER tg.sm_bi")
w("direct DELETE FROM tg")
w("direct DELETE FROM au")
w("# --- UPDATE, DELETE and INSTEAD OF")
w("direct INSERT INTO tg VALUES (4, 'd')")
w(trigger("big_au", "AFTER UPDATE"))
w("direct UPDATE tg SET s = 'e'")
w("query SELECT n, s FROM tg")
w("query SELECT m FROM au")
w("direct DROP TRIGGER tg.big_au")
w(trigger("big_bd", "BEFORE DELETE"))
w("direct DELETE FROM tg")
w("query SELECT n FROM tg")
w("query SELECT m FROM au")
w("direct DROP TRIGGER tg.big_bd")
w(trigger("big_id", "INSTEAD OF DELETE"))
w("direct DELETE FROM tg")
w("query SELECT n FROM tg")
w("query SELECT m FROM au")
w("direct DROP TRIGGER tg.big_id")
w("direct DELETE FROM tg")
w("# --- a trigger of the table that other statements read: SELECT, a drop of the table")
w(trigger("big_ai", "AFTER INSERT"))
w("query SELECT COUNT(*) FROM tg")
w("direct INSERT INTO tg VALUES (5, 'f') /* fails */")
w("direct INSERT INTO tg VALUES (6, 'g') /* fails again */")
w("query SELECT n FROM tg")
w("# ALTER to a short script: the trigger fires again")
w("direct ALTER TRIGGER big_ai ON tg AFTER INSERT BEGIN INSERT INTO au (m) VALUES ('short'); END")
w("direct INSERT INTO tg VALUES (7, 'h')")
w("query SELECT n FROM tg")
w("query SELECT m FROM au")
w("# ALTER of a short one to 65,535 bytes: fails the same. (One that was made so,")
w("# altered short and then again 65,535, reads back whole: not matched.)")
w("direct DROP TRIGGER tg.big_ai")
w("direct CREATE TRIGGER alt_s ON tg AFTER INSERT BEGIN INSERT INTO au (m) VALUES ('alt_s'); END")
w("direct ALTER TRIGGER alt_s ON tg AFTER INSERT %s" % body(65543, "alt_s"))
w("direct INSERT INTO tg VALUES (8, 'i')")
w("query SELECT n FROM tg")
w("direct DROP TABLE tg")
w("query SELECT name FROM system.triggers")
w("# the dictionary keeps one, for its files to be compared")
w("direct CREATE TABLE tg2 (n INTEGER)")
w("direct CREATE TRIGGER big_end ON tg2 AFTER DELETE %s" % body(65543, "big_end"))
w("query SELECT name FROM system.triggers")
print("\n".join(out))
