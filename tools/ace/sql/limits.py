#!/usr/bin/env python3
"""Writes limits.txt, the script of fixtures/sql/limits.json:

    python3 limits.py > limits.txt
"""
types = [(3, "a"), (1, "n"), (2, "c"), (4, "v")]
print("# The limits on lengths, names and counts, on each table type, as SQL meets")
print("# them (generated by limits.py): fixtures/sql/limits.json, in an empty folder.")
print("# Names are 128 and 129 long, not 255 and over: a path's limit counts the")
print("# data folder's length too.")
print("stmt")
n = 0


def t(p):
    global n
    n += 1
    return "%s%d" % (p, n)


cols = ", ".join("c%d CHAR(2)" % i for i in range(1, 22))
for code, p in types:
    print("tabletype %d" % code)
    for ty in ["NCHAR(32500)", "NCHAR(32501)", "VARCHAR(65000)", "VARCHAR(65001)", "NVARCHAR(32500)",
               "NVARCHAR(32501)", "CHAR(65000)", "CHAR(65001)", "CHAR(254)", "CHAR(255)", "CHAR(0)",
               "VARCHAR(254)", "VARCHAR(255)", "VARCHAR(6)", "VARCHAR(5)", "VARCHAR(1)", "VARCHAR(0)",
               "NCHAR(0)", "NVARCHAR(1)", "NUMERIC(1,0)", "NUMERIC(2,0)", "NUMERIC(32,0)", "NUMERIC(33,0)",
               "NUMERIC(32,30)", "NUMERIC(32,31)", "NUMERIC(20,18)", "NUMERIC(20,19)", "NUMERIC(3,1)",
               "NUMERIC(2,1)", "NUMERIC(0,0)", "NUMERIC(64,0)", "NUMERIC(255,0)", "NUMERIC(256,0)",
               "NUMERIC(20,255)", "DOUBLE(2)", "DOUBLE(32)", "DOUBLE(33)", "DOUBLE(255)", "DOUBLE(256)",
               "RAW(65000)", "RAW(65001)", "VARBINARY(65000)", "VARBINARY(65001)"]:
        print("direct CREATE TABLE %s (a %s)" % (t(p), ty))
    # A name of 255 characters makes a path over 255 whatever the folder is.
    print("direct CREATE TABLE %s%s (a INTEGER)" % (p, "y" * 254))
    for ln in [10, 11, 20, 127, 128, 129, 256]:
        print("direct CREATE TABLE %s (%s INTEGER)" % (t(p), "c" * ln))
        print("direct CREATE TABLE %s%s (a INTEGER)" % (p, "x" * ln))
    tn = t(p)
    print("direct CREATE TABLE %s (%s)" % (tn, cols))
    for k in [14, 15, 16, 17, 21]:
        print("direct CREATE INDEX i%d ON %s (%s)" % (k, tn, ", ".join("c%d" % i for i in range(1, k + 1))))
    for ln in [10, 11, 128, 129]:
        print("direct CREATE INDEX %s ON %s (c1)" % ("g" * ln, tn))
    for k in [19, 20, 21]:
        print("query SELECT * FROM %s ORDER BY %s" % (tn, ", ".join("c%d" % i for i in range(1, k + 1))))
    for k in [22, 25, 40]:
        print("query SELECT * FROM %s ORDER BY %s" % (tn, ", ".join("c%d" % (i % 21 + 1) for i in range(k))))
    tn = t(p)
    print("direct CREATE TABLE %s (%s)" % (tn, cols))
    for k in range(1, 56):
        print("direct CREATE INDEX g%d ON %s (c%d, c%d)" % (k, tn, (k % 21) + 1, ((k + 3) % 21) + 1))
    tn = t(p)
    print("direct CREATE TABLE %s (a CHAR(100), b CHAR(100), c CHAR(100), d CHAR(100), e CHAR(100), f CHAR(500), g CHAR(40))" % tn)
    for i, keys in enumerate(["a", "a, b", "a, b, c, d", "a, b, c, d, e", "f", "f, a", "g, f, a, b, c, d, e", "f, f"]):
        print("direct CREATE INDEX k%d ON %s (%s)" % (i + 1, tn, keys))
    # How long a key can be: one column of each length.
    lengths = [100, 200, 240, 241, 242, 243, 244, 245, 249, 250, 251, 252, 255, 256, 257, 258, 259, 260, 300, 400, 500, 512, 513, 600,
               1000, 2000, 4000, 4050, 4070, 4080, 4081, 4082, 4083, 4084, 4090, 4096, 4100, 8000]
    tn = t(p)
    print("direct CREATE TABLE %s (%s)" % (tn, ", ".join("l%d CHAR(%d)" % (l, l) for l in lengths)))
    for l in lengths:
        print("direct CREATE INDEX l%d ON %s (l%d)" % (l, tn, l))
    tn = t(p)
    print("direct CREATE TABLE %s (a CHAR(254), b CHAR(254), c CHAR(254), d CHAR(254), e CHAR(254), f CHAR(10))" % tn)
    for i, keys in enumerate(["a, b", "a, b, f", "a, b, c", "a, b, c, f", "a, b, c, d", "a, b, c, d, e"]):
        print("direct CREATE INDEX m%d ON %s (%s)" % (i + 1, tn, keys))
    # A key too long for the pages of a new ADI file, and an ADI file that
    # grows to take one.
    tn = t(p)
    print("direct CREATE TABLE %s (a CHAR(300), b CHAR(2000), c CHAR(4000), d CHAR(100), e CHAR(1000))" % tn)
    for col in ["a", "d", "b", "c", "e"]:
        print("direct CREATE INDEX z%s ON %s (%s)" % (col, tn, col))
    tn = t(p)
    print("direct CREATE TABLE %s (a CHAR(300), b CHAR(2000), d CHAR(100))" % tn)
    for col in ["d", "a", "b"]:
        print("direct CREATE INDEX z%s ON %s (%s)" % (col, tn, col))
    # The page size SQL gives a new ADI file for one order of a long key.
    for k in [240, 242, 243, 300, 498, 499, 500, 1000, 1010, 2034, 2040, 4082]:
        tn = t(p)
        print("direct CREATE TABLE %s (a CHAR(%d))" % (tn, k))
        print("direct CREATE INDEX s%d ON %s (a)" % (k, tn))
