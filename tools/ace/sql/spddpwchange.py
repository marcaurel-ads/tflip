 ("ad", "direct EXECUTE PROCEDURE sp_ModifyUserProperty('ADSSYS', 'USER_PASSWORD', 'newpassw')"),
 ("ad", "direct EXECUTE PROCEDURE sp_ModifyUserProperty('{u}', 'REQUIRE_OLD_PASSWORD', 'F')"),
 ("al", "direct EXECUTE PROCEDURE sp_ModifyUserProperty('{u}', 'USER_PASSWORD', 'newpassw')"),
