for u, noold in users:
    w("direct EXECUTE PROCEDURE sp_CreateUser('%s', 'oldpassw', '')" % u)
    if noold: w("direct EXECUTE PROCEDURE sp_ModifyUserProperty('%s', 'REQUIRE_OLD_PASSWORD', 'F')" % u)
    if u.startswith("a"):
        i = int(u[1:]); who = A[i - 1][0]
        if who != "ADSSYS":
            r = who + str(i)
            w("direct EXECUTE PROCEDURE sp_CreateUser('%s', 'oldpassw', '')" % r)
            if who == "ad": w("direct EXECUTE PROCEDURE sp_AddUserToGroup('%s', 'DB:Admin')" % r)
            else:
                w("direct GRANT ALTER ON %s TO %s" % (u, r))
w("query SELECT Name, Require_Old_Password FROM system.users")
w("disconnect")
def check(u, base="oldpassw"):
    for pw in ("newpassw", base):
        w("connect de\\de.add %s %s" % (u, pw))
        w("disconnect")
def attempt(who, u, body, base="oldpassw"):
    w("connect de\\de.add %s oldpassw" % who)
    w("stmt")
    for line in body.split("\n"):
        w(line.replace("{u}", u).replace("{U}", u.upper()).replace(" wrong #1104", " %s wrong" % u if False else " wrong #1104"))
    w("disconnect")
for i, b in enumerate(R):
    u = "r%d" % (i + 1)
    # for 1104 the user argument is the old password in the third slot: AdsDDSetUserProperty h <old> 1104 <new> len
    attempt(u, u, b)
    check(u)
for i, b in enumerate(N):
    u = "n%d" % (i + 1)
    attempt(u, u, b)
    check(u)
for i, (who, b) in enumerate(A):
    u = "a%d" % (i + 1)
    if who == "ADSSYS":
        w("connect de\\de.add ADSSYS")
        w("stmt")
        for line in b.split("\n"): w(line.replace("{u}", u))
        w("disconnect")
    else:
        r = who + str(i + 1)
        b = b.replace("{w}", r)
        attempt(r, u, b)
        check(r)
    check(u)
    if "ADSSYS'" in b and who == "ad":
        w("connect de\\de.add ADSSYS newpassw"); w("disconnect"); w("connect de\\de.add ADSSYS"); w("disconnect")
for u in ["victim"]:
    check(u)
w("connect de\\de.add ADSSYS")
w("stmt")
w("query SELECT Name, Require_Old_Password FROM system.users")
w("ddapi AdsDDSetUserProperty wrong #1104 adminpw1 #L")
w("disconnect")
for pw in ("adminpw1", ""):
    w("connect de\\de.add ADSSYS %s" % pw); w("disconnect")
w("connect de\\de.add ADSSYS adminpw1")
w("stmt")
w("ddapi AdsDDSetUserProperty ADSSYS #1101 adminpw2 #L")
w("direct EXECUTE PROCEDURE sp_ModifyUserProperty('ADSSYS', 'USER_PASSWORD', 'adminpw3')")
w("disconnect")
for pw in ("adminpw1", "adminpw2", "adminpw3"):
    w("connect de\\de.add ADSSYS %s" % pw); w("disconnect")
